
import os
import sqlite3
from datetime import datetime


DATABASE = "database/crypto.db"
DATABASE_URL = os.environ.get("DATABASE_URL")
USE_POSTGRES = bool(DATABASE_URL)


class PostgreSQLCursor:
    """Keep existing SQLite-style queries compatible with PostgreSQL."""

    def __init__(self, cursor):
        self._cursor = cursor

    def execute(self, query, params=None):
        # Convert SQLite placeholders to PostgreSQL placeholders.
        query = query.replace("?", "%s")

        if params is None:
            self._cursor.execute(query)
        else:
            self._cursor.execute(query, params)

        return self

    def __getattr__(self, name):
        return getattr(self._cursor, name)


class PostgreSQLConnection:
    """Provide the connection methods used by the existing application."""

    def __init__(self, connection):
        self._connection = connection

    def cursor(self):
        return PostgreSQLCursor(self._connection.cursor())

    def commit(self):
        return self._connection.commit()

    def rollback(self):
        return self._connection.rollback()

    def close(self):
        return self._connection.close()

    def __getattr__(self, name):
        return getattr(self._connection, name)


def get_connection():
    if USE_POSTGRES:
        import psycopg
        from psycopg.rows import dict_row

        database_url = DATABASE_URL

        # Support Render URLs that use the older postgres:// prefix.
        if database_url.startswith("postgres://"):
            database_url = "postgresql://" + database_url[len("postgres://"):]

        connection = psycopg.connect(
            database_url,
            row_factory=dict_row
        )

        return PostgreSQLConnection(connection)

    connection = sqlite3.connect(DATABASE)
    connection.row_factory = sqlite3.Row
    return connection


def initialize_database():
    connection = get_connection()
    cursor = connection.cursor()

    if USE_POSTGRES:
        cursor.execute("""
            CREATE TABLE IF NOT EXISTS users (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                username TEXT UNIQUE NOT NULL,
                email TEXT UNIQUE NOT NULL,
                password TEXT NOT NULL
            )
        """)

        cursor.execute("""
            CREATE TABLE IF NOT EXISTS history (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                user_id INTEGER,
                filename TEXT,
                action TEXT,
                date_time TEXT,
                status TEXT,
                FOREIGN KEY (user_id) REFERENCES users(id)
            )
        """)

        cursor.execute("""
            CREATE TABLE IF NOT EXISTS api_tokens (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                user_id INTEGER NOT NULL,
                token TEXT UNIQUE NOT NULL,
                created_at TEXT NOT NULL,
                FOREIGN KEY (user_id) REFERENCES users(id)
            )
        """)

    else:
        cursor.execute("""
            CREATE TABLE IF NOT EXISTS users (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                username TEXT UNIQUE NOT NULL,
                email TEXT UNIQUE NOT NULL,
                password TEXT NOT NULL
            )
        """)

        cursor.execute("""
            CREATE TABLE IF NOT EXISTS history (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                user_id INTEGER,
                filename TEXT,
                action TEXT,
                date_time TEXT,
                status TEXT,
                FOREIGN KEY (user_id) REFERENCES users(id)
            )
        """)

        cursor.execute("""
            CREATE TABLE IF NOT EXISTS api_tokens (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                user_id INTEGER NOT NULL,
                token TEXT UNIQUE NOT NULL,
                created_at TEXT NOT NULL,
                FOREIGN KEY (user_id) REFERENCES users(id)
            )
        """)

    connection.commit()
    connection.close()


def add_history(user_id, filename, action, status):
    connection = get_connection()
    cursor = connection.cursor()

    cursor.execute("""
        INSERT INTO history
        (user_id, filename, action, date_time, status)
        VALUES (?, ?, ?, ?, ?)
    """, (
        user_id,
        filename,
        action,
        datetime.now().strftime("%d-%m-%Y %H:%M:%S"),
        status
    ))

    connection.commit()
    connection.close()


def get_user_history(user_id):
    connection = get_connection()
    cursor = connection.cursor()

    cursor.execute("""
        SELECT filename, action, date_time, status
        FROM history
        WHERE user_id = ?
        ORDER BY id DESC
    """, (user_id,))

    records = cursor.fetchall()
    connection.close()

    return records


def get_user_stats(user_id):
    connection = get_connection()
    cursor = connection.cursor()

    cursor.execute("""
        SELECT
            COUNT(*) AS total_operations,
            SUM(
                CASE WHEN action = 'Encryption'
                THEN 1 ELSE 0 END
            ) AS encryption_count,
            SUM(
                CASE WHEN action = 'Decryption'
                THEN 1 ELSE 0 END
            ) AS decryption_count,
            SUM(
                CASE WHEN status = 'Success'
                THEN 1 ELSE 0 END
            ) AS success_count,
            SUM(
                CASE WHEN status != 'Success'
                THEN 1 ELSE 0 END
            ) AS failed_count
        FROM history
        WHERE user_id = ?
    """, (user_id,))

    stats = cursor.fetchone()
    connection.close()

    return stats